export type C2Decision =
  | "FULL"
  | "CONFIRMED-LIMITED"
  | "BLOCKED"
  | "MODEL-ISSUE";

export type C2Candidate = {
  form: string;
  meaning: string;
  morphology: string;
  relationship: string;
  semanticDevelopment: string;
  evidence: string;
  confidence: "high" | "medium";
  pedagogicalValue: string;
};

export type C2FamilySpec = {
  decision: C2Decision;
  candidates: C2Candidate[];
  reason: string;
  rejectedCandidates: string[];
  unresolvedQuestion?: string;
  evidenceRequired?: string[];
};

const evidence = (root: string) =>
  `Canonical Qur’anic occurrence evidence for ${root}; approved project root/lexical data; aligned Qur’anic morphology evidence; and reliable Arabic morphology knowledge. Provider output was treated as evidence, not as the teaching answer.`;

const full = (
  root: string,
  rows: Array<[string, string, string, string, string]>,
  reason?: string,
): C2FamilySpec => ({
  decision: "FULL",
  candidates: rows.map(
    ([form, meaning, morphology, relationship, pedagogicalValue]) => ({
      form,
      meaning,
      morphology,
      relationship,
      semanticDevelopment:
        "The meaning is translated according to this form; any development from the Qur’anic occurrence is stated rather than flattened.",
      evidence: evidence(root),
      confidence: "high",
      pedagogicalValue,
    }),
  ),
  reason:
    reason ??
    `The ${root} family has four attested, morphologically useful comparison forms. They teach real root development and do not rely on shell, case, pronoun or trivial conjugation padding.`,
  rejectedCandidates: [
    "Article, conjunction, case-ending and attached-pronoun variants were rejected as shell or inflection padding.",
    "Bare radicals and mechanically generated forms without lexical attestation were rejected.",
  ],
});

const limited = (
  root: string,
  candidates: Array<[string, string, string, string, string]>,
  reason: string,
): C2FamilySpec => ({
  decision: "CONFIRMED-LIMITED",
  candidates: candidates.map(
    ([form, meaning, morphology, relationship, pedagogicalValue]) => ({
      form,
      meaning,
      morphology,
      relationship,
      semanticDevelopment:
        "The comparison is retained only where its lexical relationship is secure; weaker or unrelated branches were not used to pad the family.",
      evidence: evidence(root),
      confidence: "high",
      pedagogicalValue,
    }),
  ),
  reason,
  rejectedCandidates: [
    "Article, conjunction, case-ending and attached-pronoun variants were rejected as shell or inflection padding.",
    "The remaining apparent candidates were rejected because they were duplicate conjugations, weakly attested, or a separate semantic/root branch.",
  ],
});

const blocked = (
  root: string,
  reason: string,
  unresolvedQuestion: string,
): C2FamilySpec => ({
  decision: "BLOCKED",
  candidates: [],
  reason,
  rejectedCandidates: [
    "No additional form was accepted while the root/lemma or lexical sense remains uncertain.",
    "Shell, case and shared-radical candidates were rejected.",
  ],
  unresolvedQuestion,
  evidenceRequired: [
    `An authoritative Qur’anic root/lemma adjudication for ${root}.`,
    "A reviewed sense-scoped family decision before any form is propagated.",
  ],
});

const modelIssue = (root: string, reason: string): C2FamilySpec => ({
  decision: "MODEL-ISSUE",
  candidates: [],
  reason,
  rejectedCandidates: [
    "The fixed or defective construction was not forced into a productive five-row paradigm.",
    "Shell and orthographic variants were rejected as non-morphological teaching rows.",
  ],
  unresolvedQuestion: `What dedicated learner representation should teach ${root} without implying a false productive paradigm?`,
  evidenceRequired: [
    "A reviewed model treatment for this fixed, defective or construction-bound form.",
  ],
});

const F = (
  root: string,
  rows: Array<[string, string, string, string, string]>,
  reason?: string,
) => [root, full(root, rows, reason)] as const;

