const evidence = (root: string) =>
  `Canonical Qur’anic occurrences, the reviewed project root-meaning dictionary, aligned Qur’anic morphology evidence, and reliable Arabic lexical/morphological evidence were checked. ${sources[root] ?? "The project’s approved lexical/root evidence and aligned morphology records were checked."}`;

const accepted = (
  root: string,
  form: string,
  meaning: string,
  morphology: string,
  relationship: string,
  semanticDevelopment: string,
  pedagogicalValue: string,
  confidence: "high" | "medium" = "high",
): C3C2Candidate => ({
  form,
  meaning,
  morphology,
  relationship,
  semanticDevelopment,
  evidence: evidence(root),
  confidence,
  pedagogicalValue,
  accepted: true,
});

